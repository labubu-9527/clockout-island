import { act, StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { mockIPC, mockWindows } from "@tauri-apps/api/mocks";
import { I18nProvider } from "../../src/i18n";
import { useIslandTodos } from "../../src/windows/island/useIslandTodos";
import { TodoNotebook } from "../../src/features/todos/TodoNotebook";
import { DEFAULT_SETTINGS } from "../../src/features/appearance/settingsDefaults";
import { getLocalDateString } from "../../src/utils/date";
import { TODOS_STORAGE_KEY, SCHEDULED_TODOS_STORAGE_KEY, TODO_DATE_STORAGE_KEY, TODO_SAVE_DIRECTORY_STORAGE_KEY } from "../../src/features/todos/storage";
import "../../src/styles/tokens.css";
import "../../src/styles/base.css";
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
const original = new Map(Object.entries(localStorage));
for (const key of Object.keys(localStorage).filter((key) => key.startsWith("focusd-island-"))) localStorage.removeItem(key);
let now = Date.now();
const realNow = Date.now;
Date.now = () => now;
let sounds = 0;
let opens = 0;
let quiet = false;
let visible = true;
let enabled = true;
let version = 0;
const realAudio = window.Audio;
Object.defineProperty(window, "Audio", { configurable: true, value: class { volume = 1; play() { sounds++; return Promise.resolve(); } } });
mockIPC((command) => command === "plugin:window|is_visible" ? visible : null, { shouldMockEvents: true });
mockWindows("main");
localStorage.setItem(TODO_DATE_STORAGE_KEY, getLocalDateString());
localStorage.setItem(TODO_SAVE_DIRECTORY_STORAGE_KEY, "");
const settings = () => ({ ...DEFAULT_SETTINGS, todoEnabled: enabled, carryOverIncompleteTodos: false, todoTimerEnabled: false });
let state!: ReturnType<typeof useIslandTodos>;
const navigation = { collapseIsland: () => {}, openIslandPage: () => { opens++; } };
function Harness() {
  state = useIslandTodos({ settings: settings(), navigation, quiet });
  return <TodoNotebook {...state.notebookProps} enableTodoReorder={false} scrollStartRows={5} />;
}
const root = createRoot(document.getElementById("root")!);
const mount = () => act(async () => { root.render(<StrictMode key={version}><I18nProvider><Harness /></I18nProvider></StrictMode>); });
const restart = async () => { version++; await mount(); };
const advance = async (ms: number) => { now += ms; await act(async () => { await new Promise((resolve) => setTimeout(resolve, 1150)); }); };
const input = () => document.querySelector<HTMLInputElement>(".todo-form input")!;
const type = (value: string) => act(async () => {
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value")!.set!.call(input(), value);
  input().dispatchEvent(new Event("input", { bubbles: true }));
});
const add = () => act(async () => { document.querySelector(".todo-form")!.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })); });
const messages: string[] = [];
const check = (value: unknown, label: string) => { if (!value) throw new Error(label); messages.push(`PASS ${label}`); };
const items = () => JSON.parse(localStorage.getItem(TODOS_STORAGE_KEY) ?? "[]") as { id: string; title: string; reminded?: boolean; remindAt?: number }[];
try {
  await mount();
  await type("今天整理文档"); await add();
  check(items()[0].title === "今天整理文档" && items()[0].remindAt === undefined, "Ordinary day-word task keeps its text");
  await type("0分钟后错误"); await add();
  check(document.querySelector('[role="alert"]') && input().value === "0分钟后错误" && items().length === 1, "Invalid reminder shows error and cannot submit");
  const absolute = new Date(now + 120000);
  absolute.setSeconds(0, 0);
  const absoluteDraft = `${getLocalDateString(absolute)} ${absolute.getHours()}:${String(absolute.getMinutes()).padStart(2, "0")} Expiring draft`;
  await type(absoluteDraft);
  check(document.querySelector('[role="status"]')?.textContent?.includes("Expiring draft"), "Future absolute draft starts with a valid preview");
  const beforeSubmit = now;
  now = absolute.getTime() + 1;
  await add();
  check(document.querySelector('[role="alert"]') && input().getAttribute("aria-invalid") === "true" && input().value === absoluteDraft && items().length === 1, "Submitting after the draft deadline shows a visible error and retains input");
  now = beforeSubmit;
  await type("in 1 minute Drink water");
  check(document.querySelector('[role="status"]')?.textContent?.includes("Drink water"), "Explicit reminder shows a preview");
  check(state.todoListHeight !== null && state.todoListHeight >= document.querySelector<HTMLElement>(".todo-item")!.offsetHeight + document.querySelector<HTMLElement>(".todo-reminder-preview")!.offsetHeight, "Preview contributes to island height measurement");
  await add();
  check(items()[0].title === "Drink water" && items()[0].remindAt === now + 60000 && document.querySelector("time"), "Enter creates persisted reminder with displayed time");
  await advance(59999); check(sounds === 0, "No early reminder");
  quiet = true; await mount(); await advance(1);
  check(sounds === 0 && !items()[0].reminded, "Quiet mode defers notification");
  quiet = false; visible = false; await mount(); await advance(1);
  check(sounds === 0 && !items()[0].reminded, "Hidden tray window defers sound and expansion");
  visible = true; enabled = false; await mount(); await advance(1);
  check(sounds === 0 && !items()[0].reminded, "Disabled todos defer notification");
  enabled = true; await mount(); await advance(1);
  check(sounds === 1 && opens === 1 && items()[0].reminded, "Due reminder sounds and opens the real todo page exactly once");
  await restart(); await advance(1);
  check(sounds === 1, "Restart preserves delivered marker");
  await type("1分钟后取消"); await add();
  const cancelId = items()[0].id;
  await act(async () => { state.notebookProps.onToggleTodo(cancelId); });
  await advance(60000); check(sounds === 1, "Completed reminder cancels its deadline");
  await type("1分钟后删除"); await add();
  await act(async () => { state.notebookProps.onDeleteTodo(items()[0].id); });
  await advance(60000); check(sounds === 1, "Deleted reminder cancels its deadline");
  const overdue = { id: "overdue", title: "Restart catch-up", date: getLocalDateString(), createdAt: now, remindAt: now - 1, reminded: false };
  localStorage.setItem(SCHEDULED_TODOS_STORAGE_KEY, JSON.stringify([overdue]));
  await restart(); await advance(1);
  check(sounds === 2 && items().some((item) => item.id === "overdue" && item.reminded), "Overdue scheduled reminder moves to today and catches up after restart");
  const previous = new Date(); previous.setDate(previous.getDate() - 1);
  localStorage.setItem(TODO_DATE_STORAGE_KEY, getLocalDateString(previous));
  localStorage.setItem(TODOS_STORAGE_KEY, JSON.stringify([{ id: "rollover", title: "Pending across days", completed: false, createdAt: now, remindAt: now - 1 }]));
  await restart(); await advance(1);
  check(sounds === 3 && items().some((item) => item.id === "rollover" && item.reminded), "Daily rollover preserves pending reminder even with carry-over disabled");
  document.getElementById("results")!.textContent = messages.join("\n");
  document.getElementById("results")!.dataset.result = "passed";
} catch (error) {
  document.getElementById("results")!.textContent = `${messages.join("\n")}\nFAIL ${String(error)}`;
  document.getElementById("results")!.dataset.result = "failed";
  console.error(error);
} finally {
  await act(async () => root.unmount());
  Date.now = realNow;
  Object.defineProperty(window, "Audio", { configurable: true, value: realAudio });
  for (const key of Object.keys(localStorage)) localStorage.removeItem(key);
  for (const [key, value] of original) localStorage.setItem(key, value);
}
